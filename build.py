# -*- coding: utf-8 -*-
"""Assemble client.js from src/*.js + data/seed.json.

The client half runs inside the DSH web bundle loader: no bundler, no imports.
Everything is concatenated into one factory closure so the src parts can share
top-level declarations. Build order is filename order.

    python build.py            # write client.js
    python build.py --check    # write, then syntax-check with node if present
"""
import hashlib
import io
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src')
SEED = os.path.join(HERE, 'data', 'seed.json')
OUT = os.path.join(HERE, 'client.js')

ORDER = ['01-util.js', '015-type.js', '02-data.js', '03-space.js', '04-web.js', '045-net.js', '05-app.js',
         '06-bg.js', '07-fx.js', '09-instrument.js', '10-boot-core.js', '11-boot-view.js', '12-code.js', '13-today.js','14-team.js', '15-hub.js']


def read(path):
    with io.open(path, 'r', encoding='utf-8') as fh:
        return fh.read()


def main():
    if not os.path.exists(SEED):
        sys.exit('missing %s' % SEED)
    seed = json.loads(read(SEED))
    if not seed.get('subjects'):
        sys.exit('seed.json has no subjects')

    parts = []
    for name in ORDER:
        path = os.path.join(SRC, name)
        if not os.path.exists(path):
            sys.exit('missing %s' % path)
        parts.append('/* ==== %s ==== */\n%s' % (name, read(path).rstrip() + '\n'))

    body = '\n'.join(parts)
    seed_json = json.dumps(seed, ensure_ascii=False, separators=(',', ':'))

    out = []
    out.append('/* Neuro-Loop 鈥?generated by build.py. Edit src/ and data/seed.json. */')
    out.append('window.__ModuleLoader__.load({')
    out.append("  id: '@local/neuro-loop',")
    out.append('  factory(require) {')
    out.append("    const React = require('react');")
    out.append('    const h = React.createElement;')
    out.append('    const SEED = %s;' % seed_json)
    out.append('')
    out.append(body)
    out.append('')
    out.append("    return { inject: ['slots', 'layout'], apply: install };")
    out.append('  }')
    out.append('});')
    text = '\n'.join(out)

    with io.open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)

    raw = text.encode('utf-8')
    ver = hashlib.sha1(raw).hexdigest()[:12]
    text = text.replace("var NL_BUILD = '';", "var NL_BUILD = '%s';" % ver, 1)
    raw = text.encode('utf-8')

    print('client.js  %d bytes  (%d subjects, %d shards)  build %s'
          % (len(raw), len(seed['subjects']), len(seed.get('shards') or []), ver))

    import json as _json
    import time as _time
    io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'version.json'), 'w', encoding='utf-8', newline='\n').write(
        _json.dumps({'build': ver, 'bytes': len(raw),
                     'builtAt': _time.strftime('%Y-%m-%dT%H:%M:%S')},
                    ensure_ascii=False, indent=2) + '\n')

    if '--check' in sys.argv:
        try:
            r = subprocess.run(['node', '--check', OUT], capture_output=True, text=True,
                                 encoding='utf-8', errors='replace')
            if r.returncode != 0:
                print(r.stdout + r.stderr)
                sys.exit(1)
            print('node --check: ok')
        except FileNotFoundError:
            print('node not found, skipped syntax check')


if __name__ == '__main__':
    main()
